/** 把不可信内容（命令输出、文件、MCP 返回值）包起来，防止提示词注入（文档一 13） */
export function untrusted(text: string): string {
  // 内容里如果伪造了结束标记，替换掉，避免提前「逃出」不可信块
  return `<untrusted>\n${text.replace(/<\/?untrusted>/gi, '[标记已移除]')}\n</untrusted>`;
}
