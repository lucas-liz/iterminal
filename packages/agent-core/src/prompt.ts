/**
 * 用户在打听系统提示词、内部规则或工具清单（第三十二轮）：命中时当轮附加 PROBE_NOTE。
 * 只是加一条提醒，误判（例如「帮我写个提示词」）也不影响正常回答。
 */
const PROBE_RE =
  /提示词|system\s*prompt|your\s+(prompt|instructions|rules|tools)|系统(指令|设定|消息)|(初始|预设|隐藏|开发者|内置)(指令|设定|规则|提示)|你的(规则|指令|设定|约束|工具|配置)|(哪些|什么|所有|全部)的?(规则|限制|约束|工具)|工具(列表|清单|名称|定义)|ignore\s+(all\s+)?(previous|above|prior)|忽略(之前|以上|上面|前面)|(复述|重复|原样|逐字|完整).{0,8}(上面|之前|前面|以上|内容|规则|指令)|(上面|之前|前面|以上)的?(内容|文字|消息|规则|指令).{0,6}(复述|重复|原样|逐字|输出|打印)|verbatim|jailbreak|越狱/i;

export function asksForPrompt(question: string): boolean {
  return PROBE_RE.test(question);
}

